//! Protobuf: one `.proto` file per schema, at `<package path>/types.proto`
//! (`example.v1` → `example/v1/types.proto`).
//!
//! - enums get a `<ENUM>_UNSPECIFIED = 0` value and prefixed value names;
//! - structs become messages, unions messages with a `oneof value`;
//! - each keys block becomes a `<Group>Keys` message of `optional` fields;
//! - services become `service` blocks for ConnectRPC / gRPC plugins;
//! - every constraint becomes a protovalidate (`buf.validate`) rule.
//!
//! Field numbers come from the IR (pinned by `id=` or `korek.lock`). Lists
//! and maps that Protobuf cannot nest get wrapper messages (`StringList`).
//!
//! Options: `file` (default `types.proto`), `protovalidate` (default
//! `true`), `buf_yaml` (default `true`: also write a `buf.yaml` with the
//! protovalidate dependency).

use core::fmt::Write as _;

use heck::ToShoutySnakeCase as _;
use korek_core::Diagnostic;
use korek_core::ir::{
    Constraints, EnumDef, Idempotency, KeyGroup, Retired, Schema, Service, StructDef, Type,
    TypeDef, TypeKind, UnionDef, format_number,
};
use korek_core::naming;
use korek_plugin::text::{GENERATED, doc_lines};
use korek_plugin::{File, GenerateRequest, GenerateResponse, Hook, Item};

/// Generator options.
#[derive(Debug, Clone)]
#[non_exhaustive]
pub struct Options {
    pub file: String,
    /// Emit `buf.validate` rules.
    pub protovalidate: bool,
    /// Also write `buf.yaml`.
    pub buf_yaml: bool,
}

impl Default for Options {
    fn default() -> Self {
        Self {
            file: "types.proto".into(),
            protovalidate: true,
            buf_yaml: true,
        }
    }
}

/// The plugin entry point (`korek-gen-proto`).
///
/// # Errors
/// On unknown or malformed options.
pub fn plugin(req: &GenerateRequest) -> Result<GenerateResponse, Diagnostic> {
    req.check_options(&["file", "protovalidate", "buf_yaml"])?;
    let mut opts = Options {
        protovalidate: req.bool_option("protovalidate", true)?,
        buf_yaml: req.bool_option("buf_yaml", true)?,
        ..Options::default()
    };
    if let Some(f) = req.options.get("file") {
        opts.file.clone_from(f);
    }
    Ok(GenerateResponse::new(generate(&req.schema, &opts, &[])))
}

/// The `buf.yaml` written next to the generated files.
pub const BUF_YAML: &str = "# Generated by korek from the schema. Do not edit.
version: v2
deps:
  - buf.build/bufbuild/protovalidate
lint:
  use:
    - STANDARD
breaking:
  use:
    - FILE
";

struct Gen<'a> {
    schema: &'a Schema,
    opts: &'a Options,
    hooks: &'a [&'a dyn Hook],
    out: String,
    /// Whether any `buf.validate` option was written (for the import).
    validates: bool,
}

/// Generates the `.proto` file (and `buf.yaml`, and hook files).
pub fn generate(schema: &Schema, opts: &Options, hooks: &[&dyn Hook]) -> Vec<File> {
    let mut g = Gen {
        schema,
        opts,
        hooks,
        out: String::new(),
        validates: false,
    };
    g.body();
    let mut out = format!(
        "// {GENERATED}\nsyntax = \"proto3\";\n\npackage {};\n",
        schema.package
    );
    if g.validates {
        out.push_str("\nimport \"buf/validate/validate.proto\";\n");
    }
    out.push_str(&g.out);
    for h in hooks {
        h.footer(schema, &mut out);
    }
    let dir = schema.package.replace('.', "/");
    let mut files = vec![File::new(format!("{dir}/{}", opts.file), out)];
    if opts.buf_yaml {
        files.push(File::new("buf.yaml", BUF_YAML));
    }
    for h in hooks {
        files.extend(h.files(schema));
    }
    files
}

fn scalar(ty: &Type) -> Option<&'static str> {
    Some(match ty {
        Type::Bool => "bool",
        Type::String => "string",
        Type::I64 => "int64",
        Type::U64 => "uint64",
        Type::F64 => "double",
        Type::Bytes => "bytes",
        _ => return None,
    })
}

/// A type usable as a list item, map value or oneof member.
fn element(ty: &Type) -> String {
    match ty {
        Type::Named(n) => n.clone(),
        Type::List(_) | Type::Map(_) => naming::proto_wrapper(ty),
        other => scalar(other).unwrap_or("bytes").to_owned(),
    }
}

/// A Protobuf string literal.
fn quote(s: &str) -> String {
    let mut o = String::from('"');
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

fn reserved(out: &mut String, retired: &[Retired], name: impl Fn(&str) -> String) {
    if retired.is_empty() {
        return;
    }
    let nums: Vec<String> = retired.iter().map(|r| r.number.to_string()).collect();
    let names: Vec<String> = retired.iter().map(|r| quote(&name(&r.name))).collect();
    let _ = writeln!(out, "  reserved {};", nums.join(", "));
    let _ = writeln!(out, "  reserved {};", names.join(", "));
}

impl Gen<'_> {
    fn body(&mut self) {
        let s = self.schema;
        for t in &s.types {
            self.out.push('\n');
            doc_lines(&mut self.out, "", "// ", t.doc.as_deref());
            match &t.kind {
                TypeKind::Enum(e) => self.enum_def(&t.name, e),
                TypeKind::Struct(st) => self.struct_def(&t.name, st),
                TypeKind::Union(u) => self.union_def(&t.name, u),
                _ => {}
            }
            self.after(Item::Type(t));
        }
        for g in &s.keys {
            self.out.push('\n');
            self.keys(g);
            self.after(Item::KeyGroup(g));
        }
        self.wrappers();
        for svc in &s.services {
            self.out.push('\n');
            self.service(svc);
            self.after(Item::Service(svc));
        }
    }

    fn after(&mut self, item: Item<'_>) {
        for h in self.hooks {
            h.after(item, &mut self.out);
        }
    }

    fn kind_of(&self, ty: &Type) -> Option<&TypeKind> {
        match ty {
            Type::Named(n) => self.schema.get(n).map(|t: &TypeDef| &t.kind),
            _ => None,
        }
    }

    fn enum_def(&mut self, name: &str, e: &EnumDef) {
        let prefix = name.to_shouty_snake_case();
        let _ = writeln!(self.out, "enum {name} {{\n  {prefix}_UNSPECIFIED = 0;");
        for v in &e.variants {
            doc_lines(&mut self.out, "  ", "// ", v.doc.as_deref());
            let _ = writeln!(
                self.out,
                "  {prefix}_{} = {};",
                v.name.to_shouty_snake_case(),
                v.number
            );
        }
        reserved(&mut self.out, &e.retired, |n| {
            format!("{prefix}_{}", n.to_shouty_snake_case())
        });
        self.out.push_str("}\n");
    }

    /// `buf.validate` rules for a field.
    fn rules(&mut self, ty: &Type, optional: bool, c: &Constraints) -> Vec<String> {
        if !self.opts.protovalidate {
            return Vec::new();
        }
        let mut r = Vec::new();
        let kind = self.kind_of(ty);
        let is_message = matches!(kind, Some(TypeKind::Struct(_) | TypeKind::Union(_)));
        if !optional && (is_message || *ty == Type::String) {
            r.push("required = true".to_owned());
        }
        if matches!(kind, Some(TypeKind::Enum(_))) {
            r.push("enum.defined_only = true".to_owned());
        }
        let prefix = match ty {
            Type::I64 => "int64",
            Type::U64 => "uint64",
            Type::F64 => "double",
            Type::String => "string",
            Type::Bytes => "bytes",
            Type::List(_) => "repeated",
            Type::Map(_) => "map",
            _ => "",
        };
        let (min_len, max_len) = match ty {
            Type::List(_) => ("min_items", "max_items"),
            Type::Map(_) => ("min_pairs", "max_pairs"),
            _ => ("min_len", "max_len"),
        };
        if let Some(n) = c.min {
            r.push(format!("{prefix}.gte = {}", format_number(n)));
        }
        if let Some(n) = c.max {
            r.push(format!("{prefix}.lte = {}", format_number(n)));
        }
        if let Some(n) = c.min_len {
            r.push(format!("{prefix}.{min_len} = {n}"));
        }
        if let Some(n) = c.max_len {
            r.push(format!("{prefix}.{max_len} = {n}"));
        }
        if let Some(p) = &c.pattern {
            r.push(format!("{prefix}.pattern = {}", quote(p)));
        }
        if !r.is_empty() {
            self.validates = true;
        }
        r.into_iter()
            .map(|r| format!("(buf.validate.field).{r}"))
            .collect()
    }

    /// One field line: `[optional|repeated] <type> <name> = <n> [rules];`.
    fn field(&mut self, ty: &Type, name: &str, number: u32, presence: bool, rules: &[String]) {
        let decl = match ty {
            Type::List(t) => format!("repeated {}", element(t)),
            Type::Map(t) => format!("map<string, {}>", element(t)),
            other => {
                let is_message = matches!(
                    self.kind_of(other),
                    Some(TypeKind::Struct(_) | TypeKind::Union(_))
                );
                let base = element(other);
                if presence && !is_message {
                    format!("optional {base}")
                } else {
                    base
                }
            }
        };
        let _ = write!(self.out, "  {decl} {name} = {number}");
        match rules {
            [] => {}
            [one] => {
                let _ = write!(self.out, " [{one}]");
            }
            many => {
                let _ = write!(self.out, " [\n    {}\n  ]", many.join(",\n    "));
            }
        }
        self.out.push_str(";\n");
    }

    fn struct_def(&mut self, name: &str, s: &StructDef) {
        let _ = writeln!(self.out, "message {name} {{");
        for f in &s.fields {
            doc_lines(&mut self.out, "  ", "// ", f.doc.as_deref());
            let rules = self.rules(&f.ty, f.optional, &f.constraints);
            self.field(&f.ty, &f.name, f.number, f.optional, &rules);
        }
        reserved(&mut self.out, &s.retired, str::to_owned);
        self.out.push_str("}\n");
    }

    fn union_def(&mut self, name: &str, u: &UnionDef) {
        let _ = writeln!(self.out, "message {name} {{\n  oneof value {{");
        if self.opts.protovalidate {
            self.out
                .push_str("    option (buf.validate.oneof).required = true;\n");
            self.validates = true;
        }
        for v in &u.variants {
            doc_lines(&mut self.out, "    ", "// ", v.doc.as_deref());
            let _ = writeln!(self.out, "    {} {} = {};", element(&v.ty), v.name, v.number);
        }
        self.out.push_str("  }\n");
        reserved(&mut self.out, &u.retired, str::to_owned);
        self.out.push_str("}\n");
    }

    fn keys(&mut self, g: &KeyGroup) {
        doc_lines(&mut self.out, "", "// ", g.doc.as_deref());
        let _ = writeln!(self.out, "message {} {{", naming::keys_type(g));
        for k in &g.keys {
            doc_lines(&mut self.out, "  ", "// ", k.doc.as_deref());
            if let Some(d) = &k.default {
                if k.doc.is_some() {
                    self.out.push_str("  //\n");
                }
                let _ = writeln!(self.out, "  // Default: {d}");
            }
            let rules = self.rules(&k.ty, true, &k.constraints);
            self.field(&k.ty, &k.ident(), k.number, true, &rules);
            for h in self.hooks {
                h.after(Item::Key(g, k), &mut self.out);
            }
        }
        reserved(&mut self.out, &g.retired, |n| n.replace('.', "_"));
        self.out.push_str("}\n");
    }

    fn wrappers(&mut self) {
        let s = self.schema;
        let mut used: Vec<(&Type, bool)> = Vec::new();
        for t in &s.types {
            match &t.kind {
                TypeKind::Struct(st) => used.extend(st.fields.iter().map(|f| (&f.ty, false))),
                TypeKind::Union(u) => used.extend(u.variants.iter().map(|v| (&v.ty, true))),
                _ => {}
            }
        }
        for g in &s.keys {
            used.extend(g.keys.iter().map(|k| (&k.ty, false)));
        }
        for w in naming::proto_wrappers(used) {
            let name = naming::proto_wrapper(&w);
            let _ = writeln!(
                self.out,
                "\n// A `{}` where Protobuf cannot nest one directly.\nmessage {name} {{",
                w.display()
            );
            self.field(&w, "values", 1, false, &[]);
            self.out.push_str("}\n");
        }
    }

    fn service(&mut self, svc: &Service) {
        doc_lines(&mut self.out, "", "// ", svc.doc.as_deref());
        let _ = writeln!(self.out, "service {} {{", svc.name);
        for r in &svc.rpcs {
            doc_lines(&mut self.out, "  ", "// ", r.doc.as_deref());
            let _ = write!(self.out, "  rpc {}({}) returns ({})", r.name, r.input, r.output);
            match r.idempotency {
                Some(i) => {
                    let level = match i {
                        Idempotency::NoSideEffects => "NO_SIDE_EFFECTS",
                        Idempotency::Idempotent => "IDEMPOTENT",
                    };
                    let _ = writeln!(self.out, " {{\n    option idempotency_level = {level};\n  }}");
                }
                None => self.out.push_str(";\n"),
            }
        }
        self.out.push_str("}\n");
    }
}
