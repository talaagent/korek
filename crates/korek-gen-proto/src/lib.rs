//! Protobuf: one `.proto` file per schema, at `<package path>/types.proto`
//! (`example.v1` → `example/v1/types.proto`).
//!
//! - enums get a `<ENUM>_UNSPECIFIED = 0` value and prefixed value names;
//! - structs become messages, unions messages with a `oneof value`;
//! - each keys block becomes a `<Group>Keys` message of `optional` fields;
//! - services become `service` blocks for `ConnectRPC` / gRPC plugins;
//! - every constraint becomes a protovalidate (`buf.validate`) rule.
//!
//! Field numbers come from the IR (pinned by `id=` or `korek.lock`). Lists
//! and maps that Protobuf cannot nest get wrapper messages (`StringList`).
//!
//! Options: `file` (default `types.proto`), `protovalidate` (default
//! `true`), `buf_yaml` (default `true`: also write a `buf.yaml` with the
//! protovalidate dependency).

use core::fmt::Write as _;

use korek_gen_common::{GENERATED, comment, doc_text};
use korek_ir::naming::{self, shouty};
use korek_ir::{
    Diagnostic, EnumDef, Idempotency, KeyGroup, Retired, RuleKind, Schema, Service, StructDef,
    Type, TypeDef, TypeKind, UnionDef, Validate,
};
use korek_plugin::{File, GenerateRequest, GenerateResponse, Hook, Item};

mod rules;

/// Generator options.
#[derive(Debug, Clone)]
#[non_exhaustive]
pub struct Options {
    pub file: String,
    /// Emit `buf.validate` rules.
    pub protovalidate: bool,
    /// Also write `buf.yaml`.
    pub buf_yaml: bool,
}

impl Default for Options {
    fn default() -> Self {
        Self {
            file: "types.proto".into(),
            protovalidate: true,
            buf_yaml: true,
        }
    }
}

/// The plugin entry point (`korek-gen-proto`).
///
/// # Errors
/// On unknown or malformed options.
pub fn plugin(req: &GenerateRequest) -> Result<GenerateResponse, Diagnostic> {
    req.check_options(&["file", "protovalidate", "buf_yaml"])?;
    let mut opts = Options {
        protovalidate: req.bool_option("protovalidate", true)?,
        buf_yaml: req.bool_option("buf_yaml", true)?,
        ..Options::default()
    };
    if let Some(f) = req.options.get("file") {
        opts.file.clone_from(f);
    }
    let (files, warnings) = generate(&req.schema, &opts, &[]);
    Ok(GenerateResponse::new(files).with_diagnostics(warnings))
}

/// The `buf.yaml` written next to the generated files.
pub const BUF_YAML: &str = "# Generated by korek from the schema. Do not edit.
version: v2
deps:
  - buf.build/bufbuild/protovalidate
lint:
  use:
    - STANDARD
breaking:
  use:
    - FILE
";

struct Gen<'a> {
    schema: &'a Schema,
    opts: &'a Options,
    hooks: &'a [&'a dyn Hook],
    out: String,
    /// Whether any `buf.validate` option was written (for the import).
    validates: bool,
    /// Well-known types used (for imports).
    timestamp: bool,
    duration: bool,
    warnings: Vec<Diagnostic>,
}

/// Generates the `.proto` file (and `buf.yaml`, and hook files), and
/// warnings for rules protovalidate cannot express.
pub fn generate(
    schema: &Schema,
    opts: &Options,
    hooks: &[&dyn Hook],
) -> (Vec<File>, Vec<Diagnostic>) {
    let mut g = Gen {
        schema,
        opts,
        hooks,
        out: String::with_capacity(32 * 1024),
        validates: false,
        timestamp: false,
        duration: false,
        warnings: Vec::new(),
    };
    g.body();
    let mut out = format!(
        "// {GENERATED}\nsyntax = \"proto3\";\n\npackage {};\n",
        schema.package
    );
    let mut imports = Vec::new();
    if g.validates {
        imports.push("buf/validate/validate.proto");
    }
    if g.duration {
        imports.push("google/protobuf/duration.proto");
    }
    if g.timestamp {
        imports.push("google/protobuf/timestamp.proto");
    }
    if !imports.is_empty() {
        out.push('\n');
        for i in imports {
            let _ = writeln!(out, "import {i:?};");
        }
    }
    out.push_str(&g.out);
    for h in hooks {
        h.footer(schema, &mut out);
    }
    let dir = schema.package.replace('.', "/");
    let mut files = vec![File::new(format!("{dir}/{}", opts.file), out)];
    if opts.buf_yaml {
        files.push(File::new("buf.yaml", BUF_YAML));
    }
    for h in hooks {
        files.extend(h.files(schema));
    }
    (files, g.warnings)
}

fn scalar(ty: &Type) -> Option<&'static str> {
    Some(match ty {
        Type::Bool => "bool",
        Type::String => "string",
        Type::I32 => "int32",
        Type::I64 => "int64",
        Type::U32 => "uint32",
        Type::U64 => "uint64",
        Type::F32 => "float",
        Type::F64 => "double",
        Type::Bytes => "bytes",
        Type::Timestamp => "google.protobuf.Timestamp",
        Type::Duration => "google.protobuf.Duration",
        _ => return None,
    })
}

/// A type usable as a list item, map value or oneof member.
fn element(ty: &Type) -> String {
    match ty {
        Type::Named(n) => n.clone(),
        Type::List(_) | Type::Map(_) => naming::proto_wrapper(ty),
        other => scalar(other).unwrap_or("bytes").to_owned(),
    }
}

/// A Protobuf string literal.
pub(crate) fn quote(s: &str) -> String {
    let mut o = String::from('"');
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

fn reserved(out: &mut String, retired: &[Retired], name: impl Fn(&str) -> String) {
    if retired.is_empty() {
        return;
    }
    let nums: Vec<String> = retired.iter().map(|r| r.number.to_string()).collect();
    let names: Vec<String> = retired.iter().map(|r| quote(&name(&r.name))).collect();
    let _ = writeln!(out, "  reserved {};", nums.join(", "));
    let _ = writeln!(out, "  reserved {};", names.join(", "));
}

impl Gen<'_> {
    fn body(&mut self) {
        let s = self.schema;
        for t in &s.types {
            self.out.push('\n');
            comment(&mut self.out, "", "// ", doc_text(&t.attrs).as_deref());
            match &t.kind {
                TypeKind::Enum(e) => self.enum_def(&t.name, e),
                TypeKind::Struct(st) => self.struct_def(&t.name, st, &t.validate),
                TypeKind::Union(u) => self.union_def(&t.name, u, &t.validate),
            }
            self.after(Item::Type(t));
        }
        for g in &s.keys {
            self.out.push('\n');
            self.keys(g);
            self.after(Item::KeyGroup(g));
        }
        self.wrappers();
        for svc in &s.services {
            self.out.push('\n');
            self.service(svc);
            self.after(Item::Service(svc));
        }
    }

    fn after(&mut self, item: Item<'_>) {
        for h in self.hooks {
            h.after(item, &mut self.out);
        }
    }

    fn kind_of(&self, ty: &Type) -> Option<&TypeKind> {
        match ty {
            Type::Named(n) => self.schema.get(n).map(|t: &TypeDef| &t.kind),
            _ => None,
        }
    }

    fn enum_def(&mut self, name: &str, e: &EnumDef) {
        let prefix = shouty(&snake(name));
        let _ = writeln!(self.out, "enum {name} {{\n  {prefix}_UNSPECIFIED = 0;");
        for v in &e.variants {
            comment(&mut self.out, "  ", "// ", doc_text(&v.attrs).as_deref());
            let _ = writeln!(self.out, "  {prefix}_{} = {};", shouty(&v.name), v.number);
        }
        reserved(&mut self.out, &e.retired, |n| {
            format!("{prefix}_{}", shouty(n))
        });
        self.out.push_str("}\n");
    }

    /// `buf.validate` options for a field.
    fn rules(&mut self, ty: &Type, optional: bool, v: &Validate) -> Vec<String> {
        if !self.opts.protovalidate {
            return Vec::new();
        }
        let kind = self.kind_of(ty).cloned();
        let mut r = rules::field(ty, kind.as_ref(), v, &mut self.warnings);
        let is_message = matches!(kind, Some(TypeKind::Struct(_) | TypeKind::Union(_)))
            || matches!(ty, Type::Timestamp | Type::Duration);
        if is_message && !optional && !v.has(|k| matches!(k, RuleKind::Required)) {
            r.set("required", "true".into());
        }
        if r.is_empty() {
            return Vec::new();
        }
        self.validates = true;
        vec![format!("(buf.validate.field) = {}", r.render())]
    }

    fn note_wkt(&mut self, ty: &Type) {
        match ty {
            Type::Timestamp => self.timestamp = true,
            Type::Duration => self.duration = true,
            Type::List(t) | Type::Map(t) => self.note_wkt(t),
            _ => {}
        }
    }

    /// Message-level CEL rules (`option (buf.validate.message).cel`).
    fn message_rules(&mut self, v: &Validate) {
        if !self.opts.protovalidate {
            return;
        }
        for r in &v.rules {
            if let RuleKind::Cel { id, expression, .. } = &r.kind {
                let msg = r.message.clone().unwrap_or_else(|| format!("failed {id}"));
                let _ = writeln!(
                    self.out,
                    "  option (buf.validate.message).cel = {{\n    id: {}\n    message: {}\n    expression: {}\n  }};",
                    quote(id),
                    quote(&msg),
                    quote(expression)
                );
                self.validates = true;
            }
        }
    }

    /// One field line: `[optional|repeated] <type> <name> = <n> [rules];`.
    fn field(&mut self, ty: &Type, name: &str, number: u32, presence: bool, rules: &[String]) {
        self.note_wkt(ty);
        let decl = match ty {
            Type::List(t) => format!("repeated {}", element(t)),
            Type::Map(t) => format!("map<string, {}>", element(t)),
            other => {
                let is_message = matches!(
                    self.kind_of(other),
                    Some(TypeKind::Struct(_) | TypeKind::Union(_))
                ) || matches!(other, Type::Timestamp | Type::Duration);
                let base = element(other);
                if presence && !is_message {
                    format!("optional {base}")
                } else {
                    base
                }
            }
        };
        let _ = write!(self.out, "  {decl} {name} = {number}");
        match rules {
            [] => {}
            [one] => {
                let _ = write!(self.out, " [{one}]");
            }
            many => {
                let _ = write!(self.out, " [\n    {}\n  ]", many.join(",\n    "));
            }
        }
        self.out.push_str(";\n");
    }

    fn struct_def(&mut self, name: &str, s: &StructDef, v: &Validate) {
        let _ = writeln!(self.out, "message {name} {{");
        self.message_rules(v);
        for f in &s.fields {
            comment(&mut self.out, "  ", "// ", doc_text(&f.attrs).as_deref());
            if let Some(d) = &f.default {
                let _ = writeln!(self.out, "  // Default: {d}");
            }
            let rules = self.rules(&f.ty, f.optional || f.default.is_some(), &f.validate);
            self.field(&f.ty, &f.name, f.number, f.optional, &rules);
        }
        reserved(&mut self.out, &s.retired, str::to_owned);
        self.out.push_str("}\n");
    }

    fn union_def(&mut self, name: &str, u: &UnionDef, v: &Validate) {
        let _ = writeln!(self.out, "message {name} {{");
        self.message_rules(v);
        self.out.push_str("  oneof value {\n");
        if self.opts.protovalidate {
            self.out
                .push_str("    option (buf.validate.oneof).required = true;\n");
            self.validates = true;
        }
        for v in &u.variants {
            comment(&mut self.out, "    ", "// ", doc_text(&v.attrs).as_deref());
            let _ = writeln!(
                self.out,
                "    {} {} = {};",
                element(&v.ty),
                v.name,
                v.number
            );
        }
        self.out.push_str("  }\n");
        reserved(&mut self.out, &u.retired, str::to_owned);
        self.out.push_str("}\n");
    }

    fn keys(&mut self, g: &KeyGroup) {
        comment(&mut self.out, "", "// ", doc_text(&g.attrs).as_deref());
        let _ = writeln!(self.out, "message {} {{", naming::keys_type(g));
        for k in &g.keys {
            comment(&mut self.out, "  ", "// ", doc_text(&k.attrs).as_deref());
            if let Some(d) = k.default.as_ref().filter(|_| !k.attrs.secret) {
                if k.attrs.doc.is_some() {
                    self.out.push_str("  //\n");
                }
                let _ = writeln!(self.out, "  // Default: {d}");
            }
            let rules = self.rules(&k.ty, true, &k.validate);
            self.field(&k.ty, &k.ident(), k.number, true, &rules);
            for h in self.hooks {
                h.after(Item::Key(g, k), &mut self.out);
            }
        }
        reserved(&mut self.out, &g.retired, |n| n.replace('.', "_"));
        self.out.push_str("}\n");
    }

    fn wrappers(&mut self) {
        let s = self.schema;
        let mut used: Vec<(&Type, bool)> = Vec::new();
        for t in &s.types {
            match &t.kind {
                TypeKind::Struct(st) => used.extend(st.fields.iter().map(|f| (&f.ty, false))),
                TypeKind::Union(u) => used.extend(u.variants.iter().map(|v| (&v.ty, true))),
                TypeKind::Enum(_) => {}
            }
        }
        for g in &s.keys {
            used.extend(g.keys.iter().map(|k| (&k.ty, false)));
        }
        for w in naming::proto_wrappers(used) {
            let name = naming::proto_wrapper(&w);
            let _ = writeln!(
                self.out,
                "\n// A `{}` where Protobuf cannot nest one directly.\nmessage {name} {{",
                w.display()
            );
            self.field(&w, "values", 1, false, &[]);
            self.out.push_str("}\n");
        }
    }

    fn service(&mut self, svc: &Service) {
        comment(&mut self.out, "", "// ", doc_text(&svc.attrs).as_deref());
        let _ = writeln!(self.out, "service {} {{", svc.name);
        for r in &svc.rpcs {
            comment(&mut self.out, "  ", "// ", doc_text(&r.attrs).as_deref());
            let _ = write!(
                self.out,
                "  rpc {}({}) returns ({})",
                r.name, r.input, r.output
            );
            match r.idempotency {
                Some(i) => {
                    let level = match i {
                        Idempotency::NoSideEffects => "NO_SIDE_EFFECTS",
                        Idempotency::Idempotent => "IDEMPOTENT",
                    };
                    let _ = writeln!(
                        self.out,
                        " {{\n    option idempotency_level = {level};\n  }}"
                    );
                }
                None => self.out.push_str(";\n"),
            }
        }
        self.out.push_str("}\n");
    }
}

/// `McpServer` → `mcp_server`.
fn snake(name: &str) -> String {
    let mut out = String::new();
    for (i, c) in name.chars().enumerate() {
        if c.is_ascii_uppercase() && i > 0 {
            out.push('_');
        }
        out.push(c.to_ascii_lowercase());
    }
    out
}
