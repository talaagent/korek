//! Stable Protobuf numbers: explicit `id=` pins, else `korek.lock`.
//!
//! Every enum, struct, union and keys block is a scope of numbered items.
//! An item keeps the number the lockfile records for it; a new item gets the
//! next unused number; a removed item's number is kept as `retired` and
//! never handed out again. An explicit `id=` that disagrees with the
//! lockfile is an error: numbers only change when someone edits the lock.

use alloc::collections::BTreeMap;
use core::fmt::Write as _;
use std::collections::HashMap;

use korek_ir::codes;
use korek_ir::{Diagnostic, Retired, Schema, Span, TypeKind};

use crate::ext::Literal;
use crate::source::SourceFile;

/// The lockfile's file name in a schema directory.
pub const LOCK_FILE: &str = "korek.lock";

#[derive(Debug, Clone, Default, PartialEq, Eq)]
struct Scope {
    items: BTreeMap<String, u32>,
    retired: BTreeMap<String, u32>,
}

/// Parsed `korek.lock`.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Lock {
    scopes: BTreeMap<(String, String), Scope>,
}

impl Lock {
    /// Parses a lockfile. `file` is its index in the sources, for spans.
    ///
    /// # Errors
    /// Diagnostics for malformed entries.
    pub fn parse(src: &SourceFile, file: u32) -> Result<Self, Vec<Diagnostic>> {
        let doc = crate::syntax::parse(file, &src.path, src.contents.as_str().into()).map_err(
            |problems| {
                problems
                    .into_iter()
                    .map(|p| Diagnostic::error(codes::LOCKFILE, p.message).at(p.span, "here"))
                    .collect::<Vec<_>>()
            },
        )?;
        let mut lock = Self::default();
        let mut diags = Vec::new();
        for node in doc.nodes(file) {
            if node.name() == "version" {
                continue;
            }
            let bad = |what: &str| {
                Diagnostic::error(codes::LOCKFILE, format!("malformed lockfile entry: {what}"))
                    .at(node.span(), "here")
            };
            let Some(name) = node
                .args()
                .first()
                .and_then(|a| a.value.as_str().map(str::to_owned))
            else {
                diags.push(bad("expected `<kind> \"<Name>\" { … }`"));
                continue;
            };
            let scope = lock
                .scopes
                .entry((node.name().to_owned(), name))
                .or_default();
            for item in node.children() {
                let args = item.args();
                let (Some(Literal::String(k)), Some(Literal::Int(v))) = (
                    args.first().map(|a| &a.value),
                    args.get(1).map(|a| &a.value),
                ) else {
                    diags.push(bad("expected `item \"name\" <number>`"));
                    continue;
                };
                let Ok(v) = u32::try_from(*v) else {
                    diags.push(bad("number out of range"));
                    continue;
                };
                match item.name() {
                    "item" => scope.items.insert(k.clone(), v),
                    "retired" => scope.retired.insert(k.clone(), v),
                    _ => {
                        diags.push(bad("expected `item` or `retired`"));
                        None
                    }
                };
            }
        }
        if diags.is_empty() {
            Ok(lock)
        } else {
            Err(diags)
        }
    }

    /// The lockfile text.
    pub fn render(&self) -> String {
        let mut out = String::from(
            "// korek.lock: Protobuf field and enum value numbers. Generated by\n\
             // korek; commit it. Edit by hand only to renumber on purpose.\n\
             version 1\n",
        );
        for ((kind, name), scope) in &self.scopes {
            let _ = writeln!(out, "{kind} {name:?} {{");
            let mut all: Vec<_> = scope
                .items
                .iter()
                .map(|(k, v)| ("item", k, v))
                .chain(scope.retired.iter().map(|(k, v)| ("retired", k, v)))
                .collect();
            all.sort_by_key(|(_, _, v)| **v);
            for (what, k, v) in all {
                let _ = writeln!(out, "    {what} {k:?} {v}");
            }
            out.push_str("}\n");
        }
        out
    }
}

/// An item to number: its name and explicit id.
struct Item {
    name: String,
    id: Option<(u32, Span)>,
}

const PROTO_RESERVED: core::ops::RangeInclusive<u32> = 19_000..=19_999;

fn number_scope(
    items: &[Item],
    old: Option<&Scope>,
    diags: &mut Vec<Diagnostic>,
) -> (Vec<u32>, Scope) {
    let empty = Scope::default();
    let old = old.unwrap_or(&empty);
    let mut used: HashMap<u32, String> = HashMap::new();
    for (k, v) in old.items.iter().chain(&old.retired) {
        used.insert(*v, k.clone());
    }
    let mut numbers = vec![0; items.len()];
    let mut taken: HashMap<u32, &str> = HashMap::new();
    // Explicit ids first, then locked ones, then fresh numbers.
    for (i, it) in items.iter().enumerate() {
        let Some((id, id_span)) = it.id else { continue };
        let locked = old
            .items
            .get(&it.name)
            .or_else(|| old.retired.get(&it.name));
        if let Some(l) = locked.filter(|l| **l != id) {
            diags.push(
                Diagnostic::error(
                    codes::RENUMBERED,
                    format!(
                        "`{}` is pinned to id={id} but korek.lock records {l}",
                        it.name
                    ),
                )
                .at(id_span, "differs from the lockfile")
                .help("numbers never change silently: edit korek.lock to renumber on purpose"),
            );
        } else if let Some(other) = used.get(&id).filter(|o| **o != it.name) {
            diags.push(
                Diagnostic::error(
                    codes::ID_TAKEN,
                    format!("id={id} already belongs to `{other}` in korek.lock"),
                )
                .at(id_span, "taken"),
            );
        } else if PROTO_RESERVED.contains(&id) {
            diags.push(
                Diagnostic::error(
                    codes::INVALID_ID,
                    "ids 19000-19999 are reserved by Protobuf",
                )
                .at(id_span, "reserved"),
            );
        }
        if let Some(prev) = taken.insert(id, &it.name) {
            diags.push(
                Diagnostic::error(
                    codes::DUPLICATE_ID,
                    format!("id={id} is used by both `{prev}` and `{}`", it.name),
                )
                .at(id_span, "duplicate"),
            );
        }
        numbers[i] = id;
    }
    for (i, it) in items.iter().enumerate() {
        if numbers[i] != 0 {
            continue;
        }
        let locked = old
            .items
            .get(&it.name)
            .or_else(|| old.retired.get(&it.name));
        if let Some(l) = locked.filter(|l| !taken.contains_key(l)) {
            numbers[i] = *l;
            taken.insert(*l, &it.name);
        }
    }
    let mut next = used.keys().chain(taken.keys()).copied().max().unwrap_or(0) + 1;
    for (i, it) in items.iter().enumerate() {
        if numbers[i] != 0 {
            continue;
        }
        while PROTO_RESERVED.contains(&next) || taken.contains_key(&next) {
            next += 1;
        }
        numbers[i] = next;
        taken.insert(next, &it.name);
    }
    let mut scope = Scope::default();
    for (it, n) in items.iter().zip(&numbers) {
        scope.items.insert(it.name.clone(), *n);
    }
    for (k, v) in old.items.iter().chain(&old.retired) {
        if !scope.items.contains_key(k) && !scope.items.values().any(|n| n == v) {
            scope.retired.insert(k.clone(), *v);
        }
    }
    (numbers, scope)
}

fn retired(scope: &Scope) -> Vec<Retired> {
    let mut r: Vec<Retired> = scope
        .retired
        .iter()
        .map(|(k, v)| Retired {
            name: k.clone(),
            number: *v,
        })
        .collect();
    r.sort_by_key(|r| r.number);
    r
}

/// Numbers every item of `schema` and returns the updated lock.
pub(crate) fn assign(
    schema: &mut Schema,
    ids: &HashMap<Span, (u32, Span)>,
    old: &Lock,
    diags: &mut Vec<Diagnostic>,
) -> Lock {
    let mut new = Lock::default();
    let item = |name: &str, span: Span| Item {
        name: name.to_owned(),
        id: ids.get(&span).copied(),
    };
    for t in &mut schema.types {
        let (kind, items): (&str, Vec<Item>) = match &t.kind {
            TypeKind::Enum(e) => (
                "enum",
                e.variants.iter().map(|v| item(&v.name, v.span)).collect(),
            ),
            TypeKind::Struct(s) => (
                "struct",
                s.fields.iter().map(|f| item(&f.name, f.span)).collect(),
            ),
            TypeKind::Union(u) => (
                "union",
                u.variants.iter().map(|v| item(&v.name, v.span)).collect(),
            ),
        };
        let key = (kind.to_owned(), t.name.clone());
        let (nums, scope) = number_scope(&items, old.scopes.get(&key), diags);
        match &mut t.kind {
            TypeKind::Enum(e) => {
                e.variants
                    .iter_mut()
                    .zip(&nums)
                    .for_each(|(v, n)| v.number = *n);
                e.retired = retired(&scope);
            }
            TypeKind::Struct(s) => {
                s.fields
                    .iter_mut()
                    .zip(&nums)
                    .for_each(|(f, n)| f.number = *n);
                s.retired = retired(&scope);
            }
            TypeKind::Union(u) => {
                u.variants
                    .iter_mut()
                    .zip(&nums)
                    .for_each(|(v, n)| v.number = *n);
                u.retired = retired(&scope);
            }
        }
        new.scopes.insert(key, scope);
    }
    for g in &mut schema.keys {
        let items: Vec<Item> = g.keys.iter().map(|k| item(&k.name, k.span)).collect();
        let key = ("keys".to_owned(), g.name.clone());
        let (nums, scope) = number_scope(&items, old.scopes.get(&key), diags);
        g.keys
            .iter_mut()
            .zip(&nums)
            .for_each(|(k, n)| k.number = *n);
        g.retired = retired(&scope);
        new.scopes.insert(key, scope);
    }
    new
}
